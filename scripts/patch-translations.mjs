// ─── HTTP helpers ────────────────────────────────────────────────────────────

function apiGet(path) {
  return new Promise((resolve, reject) => {
    const req = http.request(
      {
        hostname: "localhost",
        port: 3000,
        path,
        method: "GET",
        headers: {
          Cookie: `ai_ethics_token=${TOKEN}`,
        },
      },
      (res) => {
        let data = "";
        res.on("data", (chunk) => (data += chunk));
        res.on("end", () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(new Error(`JSON parse error: ${data.slice(0, 200)}`));
          }
        });
      }
    );
    req.on("error", reject);
    req.end();
  });
}

function apiPatch(path, body) {
  return new Promise((resolve, reject) => {
    const data = JSON.stringify(body);
    const req = http.request(
      {
        hostname: "localhost",
        port: 3000,
        path,
        method: "PATCH",
        headers: {
          "Content-Type": "application/json",
          "Content-Length": Buffer.byteLength(data),
          Cookie: `ai_ethics_token=${TOKEN}`,
        },
      },
      (res) => {
        let d = "";
        res.on("data", (c) => (d += c));
        res.on("end", () => {
          try {
            resolve({ status: res.statusCode, body: JSON.parse(d) });
          } catch {
            resolve({ status: res.statusCode, body: d });
          }
        });
      }
    );
    req.on("error", reject);
    req.write(data);
    req.end();
  });
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("Fetching posts...");
  const posts = await apiGet("/api/posts");
  if (!Array.isArray(posts)) {
    console.error("Unexpected response:", posts);
    process.exit(1);
  }
  console.log(`Found ${posts.length} posts.\n`);

  let patched = 0;
  let skipped = 0;
  let missing = 0;

  for (const post of posts) {
    if (post.titleEn) {
      console.log(`SKIP (already has EN): ${post.title}`);
      skipped++;
      continue;
    }

    const translation = translations[post.title];
    if (!translation) {
      console.log(`MISSING translation: ${post.title}`);
      missing++;
      continue;
    }

    const result = await apiPatch(`/api/posts/${post._id}`, translation);
    if (result.status === 200) {
      console.log(`✓ PATCHED: ${post.title}`);
      console.log(`  → ${translation.titleEn}`);
      patched++;
    } else {
      console.error(`✗ FAILED (${result.status}): ${post.title}`, result.body);
    }
  }

  console.log(`\nDone. Patched: ${patched}, Skipped: ${skipped}, Missing: ${missing}`);
}

main().catch(console.error);
